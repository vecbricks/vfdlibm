HYPOT = ATAN.replace("Atan", "Hypot").replace("atan(DoubleVector x,",
                                              "hypot(DoubleVector x, DoubleVector y,")
HYPOT_BENCH = ATAN_BENCH.replace("Atan", "Hypot").replace("atan(", "hypot(")


def results_file(cls, runs):
    """A results file of the committed form, enough for this script: per run, a header with a
    Commit and a Vector line, a min/avg/max table and a raw section naming the class.
    runs: [(commit, MaxVectorSize, {(method, inputs): min})]."""
    out = ["# %s on a host: a title" % cls, "#", "# Reading it: by hand.", "#"]
    for n, (commit, size, mins) in enumerate(runs, 1):
        if n > 1:
            out += ["#", record.RUN_LINE % (n, len(runs)), "# A later run's title", "#"]
        out += ["# Host:        somehost", "# Commit:      %s (main)" % commit,
                "# Vector:      MaxVectorSize=%d UseAVX=3" % size, "#"]
        out += record.table(sorted((cls + "." + m, k, v, v, v) for (m, k), v in mins.items()),
                            "inputs")
        out += ["#", "# JMH version: 1.37",
                "# Benchmark: %s%s.%s" % (record.PACKAGE, cls, sorted(mins)[0][0]), ""]
    return "\n".join(out) + "\n"


def mins(arm, common, mixed, scalar=(1000.0, 1100.0)):
    return {(arm, "common"): common, (arm, "mixed"): mixed,
            ("scalarStrictMath", "common"): scalar[0], ("scalarStrictMath", "mixed"): scalar[1]}


def selftest_in(repo):
    main, jmh = "src/main/java/%s/" % PACKAGE_DIR, "src/jmh/java/%s/" % PACKAGE_DIR

    def commit(changes, message):
        for path, text in changes.items():
            full = os.path.join(repo, path)
            if text is None:
                os.remove(full)
                continue
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8") as f:
                f.write(text)
        cfg = ["-c", "user.name=t", "-c", "user.email=t@example.invalid",
               "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null"]
        subprocess.run(["git", "-C", repo] + cfg + ["add", "-A"], check=True)
        subprocess.run(["git", "-C", repo] + cfg + ["commit", "-q", "-m", message], check=True)
        return subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], check=True,
                              capture_output=True, text=True).stdout.strip()

    def body():
        record.CODE_CACHE.clear()
        lines = table(repo)
        return lines[2:lines.index("", 2)]  # the heading, the rule and the rows

    saved_arms = dict(DEFAULT_ARMS)
    subprocess.run(["git", "init", "-q", repo], check=True)
    c1 = commit({"pom.xml": record.FAKE_POM.replace(
                     "</project>", "  <scm><tag>HEAD</tag></scm>\n</project>"), main + "VFdlibm.java": VFDLIBM,
                 main + "Exp.java": EXP, jmh + "ExpBenchmark.java": EXP_BENCH,
                 main + "Atan.java": ATAN, jmh + "AtanBenchmark.java": ATAN_BENCH,
                 main + "Hypot.java": HYPOT, jmh + "HypotBenchmark.java": HYPOT_BENCH,
                 "README.md": "# r\n\nStatus.\n\n%s\n%s\n\n## Use\n" % (BEGIN, END)}, "first")
    res = "bench/results/"
    # exp on the Xeon: two runs, the second at a commit of other comments; on the EPYC, one run.
    # Files that are not read: another kind of file, a laptop's, an unknown host's.
    c2 = commit({main + "Exp.java": EXP.replace("// the entry point", "/* reworded */")},
                "comments")
    commit({res + "exp-xeon8573c-2026-11-20.txt": results_file("ExpBenchmark", [
                (c1, 64, mins("finishPreferred", 200.0, 400.0)),
                (c2, 64, mins("finishPreferred", 250.0, 500.0, (900.0, 1200.0)))]),
            res + "exp-epyc7763-2026-11-20.txt": results_file("ExpBenchmark", [
                (c1, 32, mins("finishPreferred", 300.0, 700.0))]),
            res + "exp-kinds-xeon8573c-2026-11-21.txt": results_file("ExpKindsBench", [
                (c1, 64, mins("finishPreferred", 1.0, 1.0))]),
            res + "exp-laptop-2026-11-21.txt": results_file("ExpBenchmark", [
                (c1, 32, mins("finishPreferred", 1.0, 1.0))]),
            res + "exp-epyc7763-2026-11-21.txt": "# An early file: no Commit line, no table\n",
            res + "exp-somehost-2026-11-21.txt": results_file("ExpBenchmark", [
                (c1, 32, mins("finishPreferred", 1.0, 1.0))]),
            # atan: a file that lacks the arm's mixed row.
            res + "atan-epyc7763-2026-11-20.txt": results_file("AtanBenchmark", [
                (c1, 32, {k: v for k, v in mins("finishPreferred", 500.0, 600.0).items()
                          if k != ("finishPreferred", "mixed")})])}, "files")
    got = body()
    # The minimum over both runs of each row: 900 / 200 and 1100 / 400.
    assert got == [
        "| Function | xeon8573c (AVX-512): common / mixed | epyc7763 (AVX2): common / mixed |",
        "|---|---|---|",
        "| `exp` | 4.50x / 2.75x | 3.33x / 1.57x |",
        "| `atan` | not measured | 2.00x / no finishPreferred row |",
        "| `hypot` | not measured | not measured |"], got
    note = " ".join(table(repo)[8:-2])
    assert "512 bits on xeon8573c, 256 bits on epyc7763" in note, note

    # --write puts it between the markers, and --check then passes; a figure changed by hand,
    # or a marker dropped, fails.
    write(repo, "README.md")
    assert check(repo, "README.md") == []
    text = read(repo, "README.md")
    assert text.startswith("# r\n\nStatus.\n\n" + BEGIN) and text.endswith(END + "\n\n## Use\n")
    # --write refuses while the code differs from HEAD's, at which it is compared, and an error
    # leaves the README as it was.
    with open(os.path.join(repo, main + "Exp.java"), "a", encoding="utf-8") as f:
        f.write("// not committed\n")
    try:
        write(repo, "README.md")
        raise AssertionError("--write with code not committed")
    except record.Problem as e:
        assert "commit them first" in str(e) and "Exp.java" in str(e), e
    subprocess.run(["git", "-C", repo, "checkout", "-q", "--", main + "Exp.java"], check=True)
    DEFAULT_ARMS["exp"] = "blended"
    try:
        write(repo, "README.md")
        raise AssertionError("--write with DEFAULT_ARMS wrong")
    except Mismatch:
        assert read(repo, "README.md") == text
    finally:
        DEFAULT_ARMS["exp"] = "finish"
    for old, new in (("4.50x", "4.60x"), ("| `hypot`", "| `hypotx`")):
        with open(os.path.join(repo, "README.md"), "w", encoding="utf-8") as f:
            f.write(text.replace(old, new))
        diff = check(repo, "README.md")
        assert any(l.startswith("-") and new in l for l in diff), diff
    for broken in (text.replace(END, ""), text.replace(BEGIN, BEGIN + "\n" + BEGIN)):
        with open(os.path.join(repo, "README.md"), "w", encoding="utf-8") as f:
            f.write(broken)
        try:
            check(repo, "README.md")
            raise AssertionError("no markers, and no error")
        except record.Problem as e:
            assert "has not one" in str(e), e

    # A newer file wins; a host with a file gets its column, in HOSTS's order.
    commit({res + "exp-xeon8573c-2026-11-22.txt": results_file("ExpBenchmark", [
                (c2, 64, mins("finishPreferred", 100.0, 1000.0))]),
            res + "atan-epyc9v45-2026-11-22.txt": results_file("AtanBenchmark", [
                (c2, 64, mins("finishPreferred", 125.0, 1100.0))])}, "newer")
    got = body()
    assert got[0] == ("| Function | xeon8573c (AVX-512): common / mixed | epyc9v45 (AVX-512):"
                      " common / mixed | epyc7763 (AVX2): common / mixed |"), got
    assert got[2] == "| `exp` | 10.00x / 1.10x | not measured | 3.33x / 1.57x |", got
    assert got[3] == "| `atan` | not measured | 8.00x / 1.00x | 2.00x / no finishPreferred row |"

    # Code changed under exp's benchmark: every exp file is older code, atan's are not; a
    # change in a file of no benchmark's closure changes nothing.
    commit({main + "Exp.java": EXP.replace("return x;", "return x.neg();")}, "exp's code")
    got = body()
    assert got[2] == "| `exp` | older code | not measured | older code |", got
    assert got[3] == "| `atan` | not measured | 8.00x / 1.00x | 2.00x / no finishPreferred row |"
    # A file of the new code wins over the older ones, whatever their dates.
    c4 = commit({main + "Unrelated.java": "package p;\nfinal class Unrelated {}\n"}, "other")
    commit({res + "exp-xeon8573c-2026-11-23.txt": results_file("ExpBenchmark", [
        (c4, 64, mins("finishPreferred", 450.0, 550.0))])}, "new run")
    assert body()[2] == "| `exp` | 2.22x / 2.00x | not measured | older code |"
    # The release commit's <scm><tag> changes no cell; another JMH changes them all.
    pom = read(repo, "pom.xml")
    assert pom.count("<tag>HEAD</tag>") == 1
    commit({"pom.xml": pom.replace("<tag>HEAD</tag>", "<tag>v0.2.0</tag>")}, "release")
    assert body()[2] == "| `exp` | 2.22x / 2.00x | not measured | older code |", body()
    commit({"pom.xml": pom.replace("<jmh.version>1.37", "<jmh.version>1.38")}, "jmh")
    assert body()[2:] == ["| `exp` | older code | not measured | older code |",
                          "| `atan` | not measured | older code | older code |",
                          "| `hypot` | not measured | not measured | not measured |"], body()
    commit({"pom.xml": pom}, "back")

    # Two runs at commits of different code: the file is not read (record.py would have
    # refused to join them).
    c5 = commit({main + "Atan.java": ATAN.replace("return x;", "return x.abs();")}, "atan")
    commit({res + "atan-epyc9v45-2026-11-24.txt": results_file("AtanBenchmark", [
        (c2, 64, mins("finishPreferred", 1.0, 1.0)), (c5, 64, mins("finishPreferred", 1.0, 1.0))
    ])}, "mixed runs")
    assert body()[3] == "| `atan` | not measured | older code | older code |", body()

    # A file of another species for the same host is refused, and so is one named for another
    # function's class; an unknown commit is an error, not a cell.
    for name, text, words in (
            ("exp-xeon8573c-2026-11-25.txt", results_file("ExpBenchmark", [
                (c5, 64, mins("finishPreferred", 1.0, 1.0)),
                (c5, 32, mins("finishPreferred", 1.0, 1.0))]), "two preferred species"),
            ("exp-xeon8573c-2026-11-25.txt", results_file("AtanBenchmark", [
                (c5, 64, mins("finishPreferred", 1.0, 1.0))]), "is named for exp"),
            ("hypot-xeon8573c-2026-11-25.txt", results_file("HypotBenchmark", [
                ("0" * 40, 64, mins("finishPreferred", 1.0, 1.0))]), "not in the clone")):
        commit({res + name: text}, "bad")
        try:
            body()
            raise AssertionError("not refused: " + words)
        except record.Problem as e:
            assert words in str(e), e
        commit({res + name: None}, "undo")

    # DEFAULT_ARMS against the code: a default moved in the code, a table entry moved, a
    # benchmark row that times another arm, and a function of one arm whose benchmark has two.
    for changes, arms_change, words in (
            ({main + "Exp.java": EXP.replace("live, FINISH)", "live, BLENDED)")}, {},
             "exp's default arm is blended in the code and finish"),
            ({}, {"atan": "guarded"}, "atan's default arm is finish in the code and guarded"),
            ({jmh + "ExpBenchmark.java": EXP_BENCH.replace(
                "VFdlibm.exp(DoubleVector", "Exp.expBlended(DoubleVector")}, {},
             "ExpBenchmark.finishPreferred calls expBlended"),
            ({jmh + "AtanBenchmark.java": ATAN_BENCH.replace(
                "public double[] scalarStrictMath", "public double[] blendedPreferred() {}\n"
                "  public double[] scalarStrictMath")}, {}, "which is the default"),
            ({}, {"pow": "finish"}, "DEFAULT_ARMS names pow")):
        undo = {p: read(repo, p) for p in changes}
        if changes:
            commit(changes, "arm")
        DEFAULT_ARMS.update(arms_change)
        try:
            body()
            raise AssertionError("not refused: " + words)
        except Mismatch as e:
            assert words in str(e), e
        finally:
            DEFAULT_ARMS.clear()
            DEFAULT_ARMS.update(saved_arms)
            if changes:
                commit(undo, "undo")
    body()  # and back as it was


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true",
                       help="fail if README.md's table differs from what this prints")
    group.add_argument("--write", action="store_true",
                       help="put the table between README.md's markers")
    group.add_argument("--selftest", action="store_true")
    parser.add_argument("--readme", default="README.md", help="relative to the checkout's root")
    args = parser.parse_args()
    if args.selftest:
        return selftest()
    if args.check:
        diff = check(ROOT, args.readme)
        for line in diff:
            print(line)
        if diff:
            print("bench/readme-table.py: %s's speedup table is not the results files': run"
                  " bench/readme-table.py --write and commit it" % args.readme)
            return 1
        print("bench/readme-table.py: %s's speedup table is the results files'" % args.readme)
        return 0
    if args.write:
        write(ROOT, args.readme)
        return 0
    print("\n".join(table(ROOT)))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError:
        raise  # the self-test's
    except Exception as e:
        kind = "" if isinstance(e, record.Problem) else type(e).__name__ + ": "
        print("bench/readme-table.py: error: %s%s" % (kind, e), file=sys.stderr)
        sys.exit(2)
